-- Persisted B2B accounts, attempts and sessions.
CREATE TABLE IF NOT EXISTS sbx_b2b_accounts (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email varchar(254) NOT NULL CHECK (email = btrim(email) AND email LIKE '%@%' AND split_part(email, '@', 2) = lower(split_part(email, '@', 2))),
    password_hash text NOT NULL CHECK (password_hash ~ '^[$]2[aby][$][0-9]{2}[$][./A-Za-z0-9]{53}$'),
    company_code varchar(32) NOT NULL,
    profile varchar(40) NOT NULL CHECK (profile IN ('SBX_B2B_ADMIN_EMPRESA', 'SBX_B2B_APROBADOR', 'SBX_B2B_OPERADOR', 'SBX_B2B_LECTOR_AUDITOR')),
    status varchar(12) NOT NULL DEFAULT 'ACTIVE' CHECK (status IN ('ACTIVE', 'INACTIVE', 'RESTRICTED')),
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX IF NOT EXISTS sbx_b2b_accounts_lower_idx ON sbx_b2b_accounts (lower(email));

CREATE TABLE IF NOT EXISTS sbx_b2b_login_attempts (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id bigint REFERENCES sbx_b2b_accounts(id),
    email_normalized varchar(254) NOT NULL CHECK (email_normalized = lower(btrim(email_normalized))),
    outcome varchar(24) NOT NULL CHECK (outcome IN ('INVALID_CREDENTIALS', 'RATE_LIMITED')),
    correlation_id varchar(64) NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS sbx_b2b_login_attempts_email_normalized_created_at_idx ON sbx_b2b_login_attempts (email_normalized, created_at);

CREATE TABLE IF NOT EXISTS sbx_b2b_sessions (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id bigint NOT NULL REFERENCES sbx_b2b_accounts(id),
    token_hash char(64) NOT NULL UNIQUE CHECK (token_hash ~ '^[0-9a-f]{64}$'),
    last_seen_at timestamptz NOT NULL DEFAULT now(),
    expires_at timestamptz NOT NULL,
    revoked_at timestamptz,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    CHECK (expires_at > created_at)
);

CREATE OR REPLACE FUNCTION sbx_b2b_touch_updated_at() RETURNS trigger
LANGUAGE plpgsql SET search_path = pg_catalog AS $$
BEGIN
    NEW.updated_at := now();
    RETURN NEW;
END;
$$;
REVOKE ALL ON FUNCTION sbx_b2b_touch_updated_at() FROM PUBLIC;

DROP TRIGGER IF EXISTS sbx_b2b_accounts_updated_at ON sbx_b2b_accounts;
CREATE TRIGGER sbx_b2b_accounts_updated_at BEFORE UPDATE ON sbx_b2b_accounts
    FOR EACH ROW EXECUTE FUNCTION sbx_b2b_touch_updated_at();
DROP TRIGGER IF EXISTS sbx_b2b_sessions_updated_at ON sbx_b2b_sessions;
CREATE TRIGGER sbx_b2b_sessions_updated_at BEFORE UPDATE ON sbx_b2b_sessions
    FOR EACH ROW EXECUTE FUNCTION sbx_b2b_touch_updated_at();

ALTER TABLE sbx_b2b_accounts ENABLE ROW LEVEL SECURITY;
ALTER TABLE sbx_b2b_login_attempts ENABLE ROW LEVEL SECURITY;
ALTER TABLE sbx_b2b_sessions ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON sbx_b2b_accounts, sbx_b2b_login_attempts, sbx_b2b_sessions FROM PUBLIC;
REVOKE ALL ON SEQUENCE sbx_b2b_accounts_id_seq, sbx_b2b_login_attempts_id_seq, sbx_b2b_sessions_id_seq FROM PUBLIC;

-- Explicit owner-only policies: no privileges are granted to PUBLIC.
DROP POLICY IF EXISTS sbx_b2b_accounts_owner ON sbx_b2b_accounts;
CREATE POLICY sbx_b2b_accounts_owner ON sbx_b2b_accounts TO CURRENT_USER USING (true) WITH CHECK (true);
DROP POLICY IF EXISTS sbx_b2b_login_attempts_owner ON sbx_b2b_login_attempts;
CREATE POLICY sbx_b2b_login_attempts_owner ON sbx_b2b_login_attempts FOR INSERT TO CURRENT_USER WITH CHECK (true);
DROP POLICY IF EXISTS sbx_b2b_login_attempts_read ON sbx_b2b_login_attempts;
CREATE POLICY sbx_b2b_login_attempts_read ON sbx_b2b_login_attempts FOR SELECT TO CURRENT_USER USING (true);
DROP POLICY IF EXISTS sbx_b2b_sessions_owner ON sbx_b2b_sessions;
CREATE POLICY sbx_b2b_sessions_owner ON sbx_b2b_sessions TO CURRENT_USER USING (true) WITH CHECK (true);

