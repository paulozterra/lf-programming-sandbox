-- P4 / SOL-002: PostgreSQL reminder schema with constrained priority.
CREATE TABLE public.reminders (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    text varchar(140) NOT NULL CHECK (length(btrim(text)) BETWEEN 1 AND 140),
    at time(0) without time zone NOT NULL,
    priority varchar(6) NOT NULL DEFAULT 'MEDIUM'
        CHECK (priority IN ('HIGH', 'MEDIUM', 'LOW')),
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now()
);
