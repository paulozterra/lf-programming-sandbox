#!/usr/bin/env node
// Deterministic OpenAPI -> TypeScript generation; sources are repo contracts only.
import { execFileSync } from "node:child_process";
import { existsSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import { resolve, join, basename } from "node:path";
import { fileURLToPath } from "node:url";

const frontend = resolve(fileURLToPath(new URL("..", import.meta.url)));
const specs = resolve(frontend, "../contracts");
const generated = join(frontend, "src/lib/api/generated");
mkdirSync(generated, { recursive: true });
const inputs = existsSync(specs)
  ? readdirSync(specs).filter((name) => /^[a-z][a-z0-9-]*\.openapi\.yaml$/.test(name)).sort()
  : [];
const expected = new Set(["index.ts", ...inputs.map((name) => name.replace(/\.openapi\.yaml$/, ".ts"))]);
for (const file of readdirSync(generated)) {
  if (file.endsWith(".ts") && !expected.has(file)) rmSync(join(generated, file));
}
for (const file of inputs) {
  const out = join(generated, file.replace(/\.openapi\.yaml$/, ".ts"));
  const cli = join(frontend, "node_modules/.bin/openapi-typescript");
  execFileSync(cli, [join(specs, file), "--output", out], { stdio: "inherit" });
}
const exports = inputs.map((name) => {
  const stem = name.replace(/\.openapi\.yaml$/, "");
  const binding = stem.replace(/-([a-z0-9])/g, (_, c) => c.toUpperCase());
  return `export * as ${binding} from "./${stem}";`;
});
const index = ["// Generated by npm run gen:api. Do not edit.", ...exports, ""].join("\n");
const path = join(generated, "index.ts");
if (!existsSync(path) || readFileSync(path, "utf8") !== index) writeFileSync(path, index);
