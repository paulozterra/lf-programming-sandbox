"""T18: verify and republish registered native task packages without any model.

Only the trusted native record and a GitHub-authenticated historical CP3.6
artifact can attest the expected package SHA for legacy registrations.
Never infer a missing legacy digest from the newly generated bytes.
"""
from __future__ import annotations

import hashlib
import json
from pathlib import Path
import re
import sys
import tempfile

TASK = re.compile(r"[a-z][a-z0-9_-]{0,31}\Z")
REQUEST = re.compile(r"req-[1-9][0-9]*\Z")
SHA40 = re.compile(r"[0-9a-f]{40}\Z")
SHA64 = re.compile(r"[0-9a-f]{64}\Z")
ARTIFACT = "cp36-proposal-request-packs"
MAX_PACK_BYTES = 1_500_000


class TaskPackBlocked(ValueError):
    pass


def block(reason: str):
    raise TaskPackBlocked(reason)


def paths_for(request: str, task: str) -> tuple[str, str]:
    if not REQUEST.fullmatch(request) or not TASK.fullmatch(task):
        block("TASK_PACK_SCOPE_INVALID")
    base = f"pilot/runs/{request}/proposal_requests/{task}"
    return base + ".task-pack.json", base + ".proposal-request.json"


def _read_bytes(file: Path, limit: int) -> bytes:
    if file.is_symlink() or not file.is_file() or file.stat().st_size > limit:
        block("TASK_PACK_FILE_INVALID")
    return file.read_bytes()


def verify_published_pair(root: Path, request: str, task: str, expected: str) -> list[str]:
    """Require exact sha256 over real pack bytes and companion metadata."""
    if not isinstance(expected, str) or not SHA64.fullmatch(expected):
        block("TASK_PACK_HASH_MISMATCH")
    pack_rel, meta_rel = paths_for(request, task)
    pack = _read_bytes(root / pack_rel, MAX_PACK_BYTES)
    meta = _read_bytes(root / meta_rel, 80_000)
    try:
        pair = json.loads(meta)
        json.loads(pack)
    except (UnicodeError, ValueError):
        block("TASK_PACK_FILE_INVALID")
    if (not isinstance(pair, dict) or pair.get("schema_version") !=
            "CP34_NATIVE_PROPOSAL_REQUEST_V1"
            or pair.get("task_name") != task
            or pair.get("task_spec_path") !=
            f"pilot/worker_v08/native_tasks/{task}.json"
            or pair.get("task_pack_path") != pack_rel
            or pair.get("task_pack_sha256") != expected
            or pair.get("production_authority") is not False
            or pair.get("model_invoked") is not False
            or pair.get("merge_authorized") is not False
            or hashlib.sha256(pack).hexdigest() != expected):
        block("TASK_PACK_HASH_MISMATCH")
    return [pack_rel, meta_rel]


def legacy_artifact_reference(root: Path, request: str, task: str,
                              record: Path, run, repo: str) -> dict:
    """Find immutable original pair in a completed trusted-main CP3.6 artifact.

    If no original digest can be attested, refuse to manufacture one. Only
    artifacts referring to the exact registered base and task are eligible.
    """
    pack_rel, meta_rel = paths_for(request, task)
    native = json.loads(_read_bytes(record, 200_000))
    spec = native.get("task_spec")
    if not isinstance(spec, dict) or not SHA40.fullmatch(spec.get("base_head_sha", "")):
        block("TASK_PACK_REGISTRATION_INVALID")
    response = json.loads(run("gh", "api", f"repos/{repo}/actions/workflows/"
                              "chain-lots.yml/runs?per_page=100"))
    if not isinstance(response, dict) or not isinstance(response.get("workflow_runs"), list):
        block("TASK_PACK_PROVENANCE_UNAVAILABLE")
    for item in response["workflow_runs"]:
        if (not isinstance(item, dict) or type(item.get("id")) is not int
                or item.get("status") != "completed"
                or item.get("conclusion") != "success"
                or item.get("head_branch") != "main"
                or item.get("event") != "workflow_dispatch"):
            continue
        run_id = item["id"]
        artifacts = json.loads(run("gh", "api",
                                   f"repos/{repo}/actions/runs/{run_id}/artifacts?per_page=100"))
        if not isinstance(artifacts, dict) or not isinstance(artifacts.get("artifacts"), list):
            block("TASK_PACK_PROVENANCE_UNAVAILABLE")
        if not any(isinstance(a, dict) and a.get("name") == ARTIFACT
                   and not a.get("expired", False) for a in artifacts["artifacts"]):
            continue
        with tempfile.TemporaryDirectory(prefix="t18-artifact-") as tmp:
            run("gh", "run", "download", str(run_id), "--repo", repo,
                "--name", ARTIFACT, "--dir", tmp)
            # Artifact filenames cannot supply path traversal; only read
            # expected basename and reject any symlinks / oversized content.
            folder = Path(tmp)
            meta_file = folder / (task + ".proposal-request.json")
            pack_file = folder / (task + ".task-pack.json")
            if not meta_file.exists() or not pack_file.exists():
                continue
            metadata = json.loads(_read_bytes(meta_file, 80_000))
            if (not isinstance(metadata, dict)
                    or metadata.get("task_name") != task
                    or metadata.get("task_spec_path") != str(record.relative_to(root))
                    or metadata.get("task_pack_path") != pack_rel
                    or metadata.get("base_head_sha") != spec["base_head_sha"]
                    or not SHA64.fullmatch(str(metadata.get("task_pack_sha256", "")))):
                continue
            claimed = metadata["task_pack_sha256"]
            if hashlib.sha256(_read_bytes(pack_file, MAX_PACK_BYTES)).hexdigest() != claimed:
                block("TASK_PACK_HASH_MISMATCH")
            return {"task_pack_sha256": claimed, "proposal_request": metadata,
                    "origin_run_id": run_id}
    block("TASK_PACK_PROVENANCE_UNAVAILABLE")


def regenerate_pack_from_registered_base(root: Path, request: str, task: str,
                                          reference: dict) -> list[str]:
    """Re-export the actual Worker prompt from the sealed registration base."""
    pack_rel, meta_rel = paths_for(request, task)
    record = root / f"pilot/worker_v08/native_tasks/{task}.json"
    native = json.loads(_read_bytes(record, 200_000))
    spec = native.get("task_spec")
    if not isinstance(spec, dict) or not SHA40.fullmatch(spec.get("base_head_sha", "")):
        block("TASK_PACK_REGISTRATION_INVALID")
    base = spec["base_head_sha"]
    expected = reference.get("task_pack_sha256")
    meta = reference.get("proposal_request")
    if (not isinstance(expected, str) or not SHA64.fullmatch(expected)
            or not isinstance(meta, dict)
            or meta.get("base_head_sha") != base):
        block("TASK_PACK_HASH_MISMATCH")
    import subprocess
    def git(*args):
        try:
            return subprocess.run(["git", "-C", str(root), *args], check=True,
                                  capture_output=True, text=True, timeout=120).stdout.strip()
        except (OSError, subprocess.CalledProcessError, subprocess.TimeoutExpired):
            block("TASK_PACK_BASE_UNVERIFIED")
    git("merge-base", "--is-ancestor", base, "HEAD")
    for name in ("profile.md", "skills.md", "receipt.json"):
        git("cat-file", "-e", f"{base}:.lf/worker-context/{task}/{name}")
    pack = root / pack_rel
    companion = root / meta_rel
    if pack.exists() or pack.is_symlink() or companion.exists() or companion.is_symlink():
        block("TASK_PACK_ALREADY_EXISTS")
    pack.parent.mkdir(parents=True, exist_ok=True)
    # Resolve Worker code from trusted current main, never from a proposed PR.
    sys.path.insert(0, str(root / "pilot/worker_v08"))
    from export_task_pack import export
    from register_task_context import canonical
    with tempfile.TemporaryDirectory(prefix="t18-base-") as tmp:
        source = Path(tmp) / "source"
        git("worktree", "add", "--detach", str(source), base)
        try:
            raw_spec = Path(tmp) / "task-spec.json"
            raw_spec.write_bytes(canonical(spec))
            try:
                produced = export(source, raw_spec, pack)
            except (RuntimeError, OSError, ValueError):
                block("TASK_PACK_EXPORT_FAILED")
        finally:
            git("worktree", "remove", "--force", str(source))
    if produced != expected:
        block("TASK_PACK_HASH_MISMATCH")
    companion.write_bytes(canonical(meta))
    return verify_published_pair(root, request, task, expected)
