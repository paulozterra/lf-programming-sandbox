def test_real_npm_gen_api_is_staged_and_reproducible(tmp_path):
    """Runs in frontend CI after npm ci with actual openapi-typescript binary."""
    original_modules = ROOT / "frontend/node_modules"
    if not (original_modules / ".bin/openapi-typescript").exists():
        pytest.skip("real npm ci not installed (mandatory in frontend CI)")
    root = synthetic_checkout(tmp_path)
    (root / "frontend/node_modules").symlink_to(original_modules, target_is_directory=True)
    result = integration.mechanical_derivatives(
        root, {"contracts/t25-synthetic.openapi.yaml"})
    assert result == {"generator": "npm run gen:api",
                      "paths": ["frontend/src/lib/api/generated/index.ts",
                                "frontend/src/lib/api/generated/t25-synthetic.ts"]}
    index = (root / "frontend/src/lib/api/generated/index.ts").read_text()
    generated = (root / "frontend/src/lib/api/generated/t25-synthetic.ts").read_text()
    assert 'export * as t25Synthetic from "./t25-synthetic";' in index
    assert "HIGH" in generated and "MEDIUM" in generated
    assert set(git(root, "diff", "--cached", "--name-only").splitlines()) == {
        "contracts/t25-synthetic.openapi.yaml", *result["paths"]}
    git(root, "commit", "-m", "Worker contract and CP3.5 mechanical derived")
    subprocess.run(["npm", "run", "gen:api"], cwd=root / "frontend",
                   check=True, capture_output=True)
    assert git(root, "diff", "--", "frontend/src/lib/api/generated") == ""
    assert concrete_case_violations(root) == []


