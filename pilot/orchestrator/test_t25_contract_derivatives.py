def git(root, *args):
    return subprocess.run(["git", "-C", str(root), *args],
                          text=True, check=True, capture_output=True).stdout.strip()


def synthetic_checkout(tmp_path):
    root = tmp_path / "repo"
    root.mkdir()
    git(root, "init", "-b", "main")
    git(root, "config", "user.name", "T25 Offline Test")
    git(root, "config", "user.email", "t25@example.invalid")
    for file in ("frontend/package.json", "frontend/scripts/gen-api.mjs"):
        dest = root / file
        dest.parent.mkdir(parents=True, exist_ok=True)
        dest.write_bytes((ROOT / file).read_bytes())
    output = root / "frontend/src/lib/api/generated/index.ts"
    output.parent.mkdir(parents=True)
    output.write_text("// Generated by npm run gen:api. Do not edit.\n")
    (root / "contracts").mkdir()
    (root / ".gitignore").write_text("frontend/node_modules\n")
    git(root, "add", ".")
    git(root, "commit", "-m", "synthetic baseline")
    contract = root / "contracts/t25-synthetic.openapi.yaml"
    contract.write_text(SPEC)
    git(root, "add", "contracts/t25-synthetic.openapi.yaml")
    return root


