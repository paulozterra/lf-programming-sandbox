def test_unrelated_generated_or_manual_write_is_not_admitted(tmp_path):
    root = synthetic_checkout(tmp_path)
    def hostile(args, *, cwd=None):
        if args[:3] == ["npm", "run", "gen:api"]:
            target = root / "frontend/src/manual.ts"
            target.write_text("malicious\n")
            return b""
        return integration.command(args, cwd=cwd)
    # Inject the real runner after saving it, avoiding recursive patch.
    trusted = integration.command
    def hostile_runner(args, *, cwd=None):
        if args[:3] == ["npm", "run", "gen:api"]:
            target = root / "frontend/src/manual.ts"
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_text("bad\n")
            return b""
        return trusted(args, cwd=cwd)
    with pytest.raises(derived.DerivedGenerationBlocked, match=
                       "INTEGRATION_DERIVED_GENERATION_FAILED:gen:api"):
        derived.generate(root, {"contracts/t25-synthetic.openapi.yaml"}, hostile_runner)


def ci_response(*, conclusion="failure", branch=BRANCH, sha=PR_SHA):
    return {"id": CI_RUN, "head_sha": sha, "head_branch": branch,
            "status": "completed", "conclusion": conclusion,
            "event": "workflow_dispatch", "run_attempt": 1,
            "path": ".github/workflows/ci.yml",
            "repository": {"full_name": REPO}}


@pytest.mark.parametrize("logs,failed_job,expected", [
    ("FAILED: T2_CONCRETE_CASE_IN_PRODUCTION:contracts/sbx-rem-list.openapi.yaml:SBX-REM-LIST",
     "Worker pilot (offline budget, policy, vendor integrity)", "CI_DERIVED_T2"),
    ("Run git diff --exit-code -- frontend/src/lib/api/generated\n"
     "Process completed with exit code 1",
     "frontend (lint, tipos, build)", "CI_DERIVED_GEN_API"),
])
def test_only_sha_attested_mechanical_ci_red_causes_retirement(logs, failed_job, expected):
    calls = []
    def api(path):
        if path == "actions/workflows/ci.yml/runs?head_sha=" + PR_SHA + "&per_page=100":
            return {"workflow_runs": [ci_response()]}
        if path == f"actions/runs/{CI_RUN}/jobs?per_page=100":
            return {"jobs": [{"name": failed_job, "conclusion": "failure"}]}
        raise AssertionError(path)
    def run(*args):
        calls.append(args)
        assert args[:3] == ("gh", "run", "view")
        return logs
    assert recovery._ci_derived_failure(227, BRANCH, PR_SHA, run, api, REPO).startswith(expected)
    assert all(x[:3] == ("gh", "run", "view") for x in calls)
    assert recovery._ci_derived_failure(
        227, BRANCH, "c" * 40, run,
        lambda path: {"workflow_runs": [ci_response()]}, REPO) is None


